const REC = [];
const RMAP = new WeakMap();
const _addSlide = pres.addSlide.bind(pres);
pres.addSlide = function(){
  const sl = _addSlide();
  const r = { bg:'FFFFFF', items:[], notes:'' };
  REC.push(r); RMAP.set(sl, r);
  ['addText','addShape','addImage'].forEach(n=>{
    const f = sl[n].bind(sl);
    sl[n] = function(...a){ r.items.push({ t:n, a:JSON.parse(JSON.stringify(a)) }); return f(...a); };
  });
  const fn = sl.addNotes.bind(sl);
  sl.addNotes = function(t){ r.notes = t; return fn(t); };
  return sl;
};


/* ---------- helpers ---------- */
