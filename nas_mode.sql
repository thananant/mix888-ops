-- nas_mode.sql — สวิตช์แบ่งงานวาดบิลระหว่างตัวทำงานบน NAS กับ edge function (ใช้กับ cron-42 ขึ้นไป)
-- '1' = โหมด NAS: การวาดรูปพื้นหลังใน ?autobill=1 จะเลือกเฉพาะบิลที่เก่ากว่า 10 นาที
--       เปิดทางให้ NAS (เทมเพลต 2 หน้าตาเดียวกับเบราว์เซอร์ · ไม่มีเพดานซีพียู) จับวาดก่อน
--       edge ยังเป็นตัวเก็บตกใบที่ NAS วาดไม่ทันเหมือนเดิม
-- '0' = ระบบวาดด้วย edge อย่างเดียวเหมือนเดิม (ค่าตั้งต้น)
-- ⚠️ ตั้งเป็น '1' เฉพาะ "หลังจาก" คอนเทนเนอร์ NAS รันจริงแล้วเท่านั้น — ถ้าเปิดก่อนมี NAS
--    บิลใหม่ทุกใบจะต้องรอเกิน 10 นาทีกว่า edge จะยอมวาด ทั้งที่ไม่มีใครวาดให้เร็วกว่านั้น
-- สลับ '0' กลับได้ทุกเมื่อ = คืนระบบเป็น edge วาดเองทั้งหมดทันที ไม่ต้อง deploy ใหม่

-- มีค่าอยู่แล้ว → อัปเดตทับ (เริ่มที่ '0' เสมอ)
update settings set value = '0' where key = 'nas_mode';

-- ยังไม่มี → เพิ่มใหม่ (กันรันซ้ำแล้วได้แถวซ้ำ)
insert into settings (key, value)
select 'nas_mode', '0'
where not exists (select 1 from settings where key = 'nas_mode');
